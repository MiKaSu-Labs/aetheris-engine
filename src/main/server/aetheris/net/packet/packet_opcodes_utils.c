static const size_t AE_OPCODE_TABLE_LEN =
    sizeof(AE_OPCODE_TABLE) / sizeof(AE_OPCODE_TABLE[0]);

/* =========================================================================
 * Loop packet table
 *
 * Mirrors the LOOP_PACKETS set , high-frequency packets excluded from
 * verbose logging.
 * ====================================================================== */
static const int AE_LOOP_PACKETS[] = {
    AE_OPCODE_PingReq,
    AE_OPCODE_PingRsp,
    AE_OPCODE_WorldPlayerRTTNotify,
    AE_OPCODE_UnionCmdNotify,
    AE_OPCODE_QueryPathReq,
    AE_OPCODE_QueryPathRsp,

    /* Satiation sends these every tick */
    AE_OPCODE_PlayerTimeNotify,
    AE_OPCODE_PlayerGameTimeNotify,
    AE_OPCODE_AvatarPropNotify,
    AE_OPCODE_AvatarSatiationDataNotify,
};

static const size_t AE_LOOP_PACKETS_LEN =
    sizeof(AE_LOOP_PACKETS) / sizeof(AE_LOOP_PACKETS[0]);

/* =========================================================================
 * ae_opcode_is_loop_packet()
 * ====================================================================== */
bool ae_opcode_is_loop_packet(int opcode) {
    for (size_t i = 0; i < AE_LOOP_PACKETS_LEN; i++) {
        if (AE_LOOP_PACKETS[i] == opcode) return true;
    }
    return false;
}

/* =========================================================================
 * ae_opcode_get_name()
 *
 * Binary search over AE_OPCODE_TABLE, sorted by value ascending.
 * ====================================================================== */
const char *ae_opcode_get_name(int opcode) {
    if (opcode <= 0) return "UNKNOWN";

    size_t lo = 0, hi = AE_OPCODE_TABLE_LEN;
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        int    v   = AE_OPCODE_TABLE[mid].value;
        if (v == opcode) {
            return AE_OPCODE_TABLE[mid].name;
        } else if (v < opcode) {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    return "UNKNOWN";
}

/* =========================================================================
 * ae_opcode_dump_packet_ids()
 *
 * AE_OPCODE_TABLE is already sorted by value ascending, so the dump
 * order matches the original TreeMap-sorted output with no extra
 * sorting step required.
 * ====================================================================== */
int ae_opcode_dump_packet_ids(void) {
    char filename[128];
    snprintf(filename, sizeof(filename), "./PacketIds_%s.json", ae_version);

    ae_json_builder_t *root = json_builder_object();
    if (!root) return -1;

    for (size_t i = 0; i < AE_OPCODE_TABLE_LEN; i++) {
        if (AE_OPCODE_TABLE[i].value <= 0) continue;

        char key[16];
        snprintf(key, sizeof(key), "%d", AE_OPCODE_TABLE[i].value);
        json_object_add_str(root, key, AE_OPCODE_TABLE[i].name);
    }

    char *encoded = json_builder_encode(root);
    json_builder_free(root);
    if (!encoded) return -1;

    FILE *f = fopen(filename, "wb");
    if (!f) {
        free(encoded);
        return -1;
    }
    fputs(encoded, f);
    fclose(f);
    free(encoded);

    ae_logger_info(ae_logger, "Dumped packet IDs.");
    return 0;
}
